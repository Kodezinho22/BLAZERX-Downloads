must(cloud.includes("version:'1.9.32'"),'cloud API version missing');
const compat=read('public/js/estudex-engine-socket-compat.js');
must(compat.includes('ESTUDEX_V193_HOTFIX32_CREATE_FEEDBACK'),'create feedback marker missing');
must(compat.includes('createRoomInFlightV1936'),'create duplicate guard missing');
must(compat.includes("createButton.textContent='Criando...'"),'instant create feedback missing');
must(compat.includes('ESTUDEX_V193_RECENT_ROOM_COMPAT_FAST_PATH'),'same-room navigation fast path lost');
must(sha('public/js/home.js')===manifest.preserved.homeJs,'canonical home.js changed');
